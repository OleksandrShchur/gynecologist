import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const assetsDirectory = join(projectRoot, 'src', 'assets');
const generatedDirectory = join(assetsDirectory, 'generated');
const contentDirectory = join(projectRoot, 'src', 'content');
const targetWidths = [480, 768, 1120];
const sourcePhotos = [
  { key: 'portrait', name: 'photo-portrait' },
  { key: 'standing', name: 'photo-standing' },
];

async function writeIfChanged(path, content) {
  const next = Buffer.isBuffer(content) ? content : Buffer.from(content, 'utf8');
  try {
    const previous = await readFile(path);
    if (previous.equals(next)) return;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  await writeFile(path, next);
}

async function sourceExists(path) {
  try {
    return (await stat(path)).isFile();
  } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
}

await mkdir(generatedDirectory, { recursive: true });
await mkdir(contentDirectory, { recursive: true });

const imports = [];
const entries = [];
const missing = [];

for (const source of sourcePhotos) {
  const sourcePath = join(assetsDirectory, `${source.name}.png`);
  if (!(await sourceExists(sourcePath))) {
    missing.push(`${source.name}.png`);
    continue;
  }

  const metadata = await sharp(sourcePath, { failOn: 'error' }).metadata();
  if (!metadata.width || !metadata.height) {
    throw new Error(`Не вдалося визначити розмір фото: ${source.name}.png`);
  }

  // EXIF orientations 5–8 swap width and height after automatic rotation.
  const rotated = metadata.orientation >= 5 && metadata.orientation <= 8;
  const sourceWidth = rotated ? metadata.height : metadata.width;
  const widths = [...new Set(targetWidths.map((width) => Math.min(width, sourceWidth)))];
  const variants = [];

  for (const width of widths) {
    const { data, info } = await sharp(sourcePath, { failOn: 'error' })
      .rotate()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 84, effort: 5 })
      .toBuffer({ resolveWithObject: true });

    const filename = `${source.name}-${info.width}.webp`;
    const identifier = `${source.key}${info.width}`;
    await writeIfChanged(join(generatedDirectory, filename), data);
    imports.push(`import ${identifier} from '../assets/generated/${filename}';`);
    variants.push({ identifier, width: info.width, height: info.height });
  }

  const largest = variants.at(-1);
  const sourceSet = variants.map(({ identifier, width }) => `\${${identifier}} ${width}w`).join(', ');
  entries.push(
    `  ${source.key}: {\n` +
      `    src: ${largest.identifier},\n` +
      `    srcSet: \`${sourceSet}\`,\n` +
      `    width: ${largest.width},\n` +
      `    height: ${largest.height},\n` +
      '  },',
  );
}

const moduleContent = [
  '// Generated by scripts/optimize-images.mjs. Do not edit manually.',
  ...imports,
  '',
  'export interface OptimizedPhoto {',
  '  src: string;',
  '  srcSet: string;',
  '  width: number;',
  '  height: number;',
  '}',
  '',
  'export const photos: { portrait?: OptimizedPhoto; standing?: OptimizedPhoto } = {',
  ...entries,
  '};',
  '',
].join('\n');

// Only current originals enter the module; stale generated files are never used.
await writeIfChanged(join(contentDirectory, 'images.generated.ts'), moduleContent);

if (missing.length) {
  console.info(`Фото ще не додано: ${missing.join(', ')}. Відповідні блоки фото приховано.`);
}
if (entries.length) {
  console.info(`Фото оптимізовано: ${entries.length}. WebP збережено у src/assets/generated/.`);
}

// Original decorative artwork is committed; generated responsive assets are not.
const blossomSource = join(assetsDirectory, 'story-blossom.png');
if (!(await sourceExists(blossomSource))) {
  throw new Error('Відсутнє декоративне зображення: src/assets/story-blossom.png.');
}
const blossomMetadata = await sharp(blossomSource, { failOn: 'error' }).metadata();
if (!blossomMetadata.width || !blossomMetadata.height) {
  throw new Error('Не вдалося визначити розмір декоративної квітки.');
}
const blossomRotated = blossomMetadata.orientation >= 5 && blossomMetadata.orientation <= 8;
const blossomWidth = blossomRotated ? blossomMetadata.height : blossomMetadata.width;
const blossomWidths = [...new Set([480, 768, 1200].map((width) => Math.min(width, blossomWidth)))];
const blossomImports = [];
const blossomVariants = [];

for (const width of blossomWidths) {
  const { data, info } = await sharp(blossomSource, { failOn: 'error' })
    .rotate()
    .resize({ width, withoutEnlargement: true })
    // Keep the original alpha channel; no matte, cropping, or enlargement.
    .webp({ quality: 78, alphaQuality: 95, effort: 5 })
    .toBuffer({ resolveWithObject: true });
  const filename = `story-blossom-${info.width}.webp`;
  const identifier = `storyBlossom${info.width}`;
  await writeIfChanged(join(generatedDirectory, filename), data);
  blossomImports.push(`import ${identifier} from '../assets/generated/${filename}';`);
  blossomVariants.push({ identifier, width: info.width, height: info.height });
}

const largestBlossom = blossomVariants.at(-1);
const blossomSourceSet = blossomVariants.map(({ identifier, width }) => `\${${identifier}} ${width}w`).join(', ');
const blossomModule = [
  '// Generated by scripts/optimize-images.mjs. Do not edit manually.',
  ...blossomImports,
  '',
  'export interface OptimizedStoryBlossom {',
  '  readonly src: string;',
  '  readonly srcSet: string;',
  '  readonly width: number;',
  '  readonly height: number;',
  '}',
  '',
  'export const storyBlossom: OptimizedStoryBlossom = {',
  `  src: ${largestBlossom.identifier},`,
  `  srcSet: \`${blossomSourceSet}\`,`,
  `  width: ${largestBlossom.width},`,
  `  height: ${largestBlossom.height},`,
  '};',
  '',
].join('\n');
await writeIfChanged(join(contentDirectory, 'story.generated.ts'), blossomModule);
console.info(`Декоративну квітку оптимізовано: ${blossomVariants.length} прозорі WebP.`);
